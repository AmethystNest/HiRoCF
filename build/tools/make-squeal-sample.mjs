/**
 * Builds src/audio/squealsample.js from a recording of a tyre squeal -- the
 * source for makeSampledSqueal in src/audio/sfx.js. Run with:
 *
 *   node build/tools/make-squeal-sample.mjs <recording.mp3> <from s> <to s> <sustain s>
 *
 * Cuts [from, to] -- the squeal from its onset to just before it dies --
 * sums to mono, removes DC and anything under 200 Hz (a squeal has nothing
 * there but handling rumble), and evens out its level: the recording fades
 * about 9 dB from the bite to the end, and a voice that loops the end has
 * to hold it at the same level as the start. The evening is partial
 * (gain ~ envelope^-0.85, 150 ms envelope, at most +12 dB), so the squeal's
 * own quick flutter survives. Then normalises and writes 16-bit PCM at the
 * source rate, base64, with `sustain`: where (s into the cut) the clean,
 * tonal part starts that the voice loops for as long as a slide lasts.
 * The recording itself is not in the repository.
 */
import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
import path from 'path';

const [src, fromS, toS, sustainS] = process.argv.slice(2);
if (!sustainS) { console.error('usage: make-squeal-sample.mjs <recording.mp3> <from s> <to s> <sustain s>'); process.exit(1); }
const b64 = fs.readFileSync(src).toString('base64');
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage();
await page.goto('about:blank');
const out = await page.evaluate(async ({ b64, from, to }) => {
  const bin = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
  const ctx = new OfflineAudioContext(1, 44100, 44100);
  const buf = await ctx.decodeAudioData(bin.buffer);
  const sr = buf.sampleRate, nch = buf.numberOfChannels;
  const a = Math.round(from * sr), n = Math.round(to * sr) - a;
  const x = new Float32Array(n);
  for (let c = 0; c < nch; c++) { const d = buf.getChannelData(c); for (let i = 0; i < n; i++) x[i] += d[a + i] / nch; }
  // 2nd-order high-pass at 200 Hz (RBJ biquad), which also takes out DC
  const w0 = 2 * Math.PI * 200 / sr, al = Math.sin(w0) / (2 * 0.707), cw = Math.cos(w0);
  const b0 = (1 + cw) / 2, b1 = -(1 + cw), b2 = (1 + cw) / 2, a0 = 1 + al, a1 = -2 * cw, a2 = 1 - al;
  let x1 = 0, x2 = 0, y1 = 0, y2 = 0;
  for (let i = 0; i < n; i++) { const y = (b0 * x[i] + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2) / a0; x2 = x1; x1 = x[i]; y2 = y1; y1 = y; x[i] = y; }
  // partial level evening: 150 ms RMS envelope (centred), gain env^-0.85
  const W = Math.round(0.075 * sr);
  const pre = new Float64Array(n + 1);
  for (let i = 0; i < n; i++) pre[i + 1] = pre[i] + x[i] * x[i];
  let ref = 0;
  const env = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    const a0 = Math.max(0, i - W), a1 = Math.min(n, i + W);
    env[i] = Math.sqrt((pre[a1] - pre[a0]) / (a1 - a0)) + 1e-9;
    ref = Math.max(ref, env[i]);
  }
  for (let i = 0; i < n; i++) x[i] *= Math.min(4, Math.pow(env[i] / ref, -0.85));
  // 5 ms fade-in so the first sample is not a click
  const fi = Math.round(0.005 * sr);
  for (let i = 0; i < fi; i++) x[i] *= i / fi;
  let peak = 0, e = 0; for (let i = 0; i < n; i++) { peak = Math.max(peak, Math.abs(x[i])); e += x[i] * x[i]; }
  const g = 0.95 / peak;
  const y = new Int16Array(n);
  for (let i = 0; i < n; i++) y[i] = Math.round(x[i] * g * 32767);
  let s = ''; const bytes = new Uint8Array(y.buffer); for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode.apply(null, bytes.subarray(i, i + 0x8000));
  return { rate: sr, pcm: btoa(s), secs: n / sr, rmsDb: 20 * Math.log10(Math.sqrt(e / n) * g) };
}, { b64, from: +fromS, to: +toS });
await browser.close();
const file = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../src/audio/squealsample.js');
fs.writeFileSync(file, `/**
 * GENERATED by build/tools/make-squeal-sample.mjs -- do not edit by hand.
 *
 * ${out.secs.toFixed(3)} s of a tyre squeal, onset to just before it dies, mono 16-bit PCM
 * at ${out.rate} Hz (little-endian, base64), level partly evened and normalised to 0.95 peak
 * (${out.rmsDb.toFixed(1)} dBFS RMS). \`sustain\` is where its clean tonal part starts (s),
 * which makeSqueal in sfx.js loops. Cut arguments: ${process.argv.slice(3).join(' ')}.
 */
export const SQUEAL_SAMPLE = {
  rate: ${out.rate},
  sustain: ${(+sustainS - +fromS).toFixed(3)},
  pcm: '${out.pcm}',
};
`);
console.log(JSON.stringify({ secs: out.secs, rmsDb: out.rmsDb }), 'wrote', file, (fs.statSync(file).size / 1024).toFixed(0), 'KB');
